// Renders src/data/site.ts into worker/src/context.generated.ts, the resume text the chat
// model answers from. Run with `npm run context` (also part of `npm run deploy`).
import { writeFileSync } from 'node:fs';
import { profile, skills, experience, projects, contacts } from '../../src/data/site.ts';

const lines: string[] = [];
lines.push(`NAME: ${profile.name}`, `ROLE: ${profile.role}`, `SUMMARY: ${profile.summary}`, `LOCATION: ${profile.location}`, `EMAIL: ${profile.email}`);
lines.push('LINKS: ' + profile.links.map((l) => `${l.label} ${l.href}`).join('; '));
lines.push('', 'SKILLS');
for (const [g, items] of Object.entries(skills)) lines.push(`- ${g}: ${items.join(', ')}`);
lines.push('', 'EXPERIENCE AND EDUCATION');
for (const j of experience) {
  lines.push(`- ${j.role}, ${j.org} (${j.period}): ${j.summary}`);
  if (j.titles) lines.push(`  Titles: ${j.titles.map((t) => `${t.title}${t.period ? ` (${t.period})` : ''}`).join('; ')}`);
  for (const p of j.points ?? []) lines.push(`  * ${p}`);
  if (j.stack?.length) lines.push(`  Tech: ${j.stack.join(', ')}`);
  for (const p of j.projects ?? []) {
    lines.push(`  Project ${p.name}: ${p.hook}${p.metric ? ` [${p.metric}]` : ''} ${p.details} Tech: ${p.stack.join(', ')}`);
  }
}
lines.push('', 'OPEN SOURCE AND PERSONAL PROJECTS');
for (const p of projects) lines.push(`- ${p.name}: ${p.blurb} (${p.stack.join(', ')}) ${p.href}`);
lines.push('', 'CONTACT');
for (const c of contacts) lines.push(`- ${c.label}: ${c.handle} ${c.href}`);

const text = lines.join('\n');
const out = new URL('../src/context.generated.ts', import.meta.url);
writeFileSync(out, `// GENERATED by scripts/gen-context.ts from src/data/site.ts. Do not edit by hand.\nexport const RESUME_CONTEXT = ${JSON.stringify(text)};\n`);
console.log(`wrote ${out.pathname} (${text.length} chars)`);
